BEGIN;

CREATE TABLE IF NOT EXISTS yomiru_incremental_head (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  baseline text NOT NULL REFERENCES yomiru_publication (revision),
  revision text NOT NULL,
  catalogue_revision text NOT NULL,
  serving boolean NOT NULL DEFAULT false
);

CREATE OR REPLACE FUNCTION yomiru_guard_legacy_activation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.revision IS DISTINCT FROM OLD.revision AND EXISTS (
    SELECT 1 FROM yomiru_incremental_head WHERE singleton AND serving
  ) THEN
    RAISE EXCEPTION 'Legacy publication is closed after the incremental cutover';
  END IF;
  RETURN NEW;
END;
$$;

CREATE OR REPLACE TRIGGER yomiru_guard_legacy_activation
BEFORE UPDATE OF revision ON yomiru_active FOR EACH ROW EXECUTE FUNCTION yomiru_guard_legacy_activation();

CREATE TABLE IF NOT EXISTS yomiru_incremental_change (
  revision text PRIMARY KEY,
  previous text NOT NULL,
  request_key text UNIQUE,
  payload jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS yomiru_incremental_catalogue (
  id text PRIMARY KEY,
  show_id text NOT NULL,
  ordinal bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
  search_text text NOT NULL,
  detail jsonb NOT NULL
);

CREATE INDEX IF NOT EXISTS yomiru_incremental_catalogue_show
  ON yomiru_incremental_catalogue (show_id, ordinal);

CREATE TABLE IF NOT EXISTS yomiru_incremental_metadata (
  type text NOT NULL CHECK (type IN ('movie', 'series')),
  id text NOT NULL,
  detail jsonb NOT NULL,
  PRIMARY KEY (type, id)
);

CREATE TABLE IF NOT EXISTS yomiru_incremental_track (
  id text PRIMARY KEY,
  ordinal bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,
  detail jsonb NOT NULL
);

CREATE TABLE IF NOT EXISTS yomiru_incremental_track_video (
  type text NOT NULL CHECK (type IN ('movie', 'series')),
  video_id text NOT NULL,
  track_id text NOT NULL REFERENCES yomiru_incremental_track (id),
  PRIMARY KEY (type, video_id, track_id)
);

CREATE TABLE IF NOT EXISTS yomiru_incremental_dictionary (
  id text PRIMARY KEY,
  jmdict_entry_id bigint CHECK (jmdict_entry_id > 0),
  detail jsonb NOT NULL
);

CREATE INDEX IF NOT EXISTS yomiru_incremental_dictionary_jmdict
  ON yomiru_incremental_dictionary (jmdict_entry_id) WHERE jmdict_entry_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS yomiru_incremental_dictionary_reading
  ON yomiru_incremental_dictionary ((detail ->> 'reading')) WHERE detail ? 'jmdictSenses';

CREATE TABLE IF NOT EXISTS yomiru_incremental_source_archive (
  anchor text NOT NULL,
  manifest_sha256 text NOT NULL,
  manifest jsonb NOT NULL,
  PRIMARY KEY (anchor, manifest_sha256)
);

CREATE TABLE IF NOT EXISTS yomiru_incremental_vocabulary (
  video_id text PRIMARY KEY,
  anchor text NOT NULL,
  descriptor jsonb NOT NULL,
  header jsonb NOT NULL,
  manifest_sha256 text,
  FOREIGN KEY (anchor, manifest_sha256)
    REFERENCES yomiru_incremental_source_archive (anchor, manifest_sha256)
);

CREATE TABLE IF NOT EXISTS yomiru_incremental_occurrence (
  video_id text NOT NULL REFERENCES yomiru_incremental_vocabulary (video_id),
  word_id text NOT NULL REFERENCES yomiru_incremental_dictionary (id),
  detail jsonb NOT NULL,
  PRIMARY KEY (video_id, word_id)
);

CREATE INDEX IF NOT EXISTS yomiru_incremental_occurrence_word
  ON yomiru_incremental_occurrence (word_id, video_id);

CREATE TABLE IF NOT EXISTS yomiru_incremental_word_coverage (
  word_id text PRIMARY KEY REFERENCES yomiru_incremental_dictionary (id),
  titles integer NOT NULL CHECK (titles > 0)
);

CREATE TABLE IF NOT EXISTS yomiru_incremental_word_review (
  word_id text PRIMARY KEY REFERENCES yomiru_incremental_dictionary (id),
  state text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending', 'resolved', 'needs_review')),
  lease uuid,
  leased_until timestamptz,
  attempts int NOT NULL DEFAULT 0,
  result jsonb,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((lease IS NULL) = (leased_until IS NULL))
);

CREATE INDEX IF NOT EXISTS yomiru_incremental_pending_review
  ON yomiru_incremental_word_review (updated_at, word_id) WHERE state = 'pending';

COMMIT;
